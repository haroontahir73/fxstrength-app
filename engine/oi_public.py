def main(argv):
    now = dt.datetime.now(dt.timezone.utc)
    p = write_page(now)
    view = _load()
    if view:
        for key in view["order"]:
            mt = view["markets"][key]["metrics"]
            if mt.get("available"):
                print(f"  {key:7} {mt['date']}  Fut {mt['futures_only_oi']:>10,}  "
                      f"FE {mt['options_fe_oi']:>9,}  Comb {mt['combined_oi']:>10,}  "
                      f"share {mt['options_share'] * 100:4.1f}%")
    print(f"  wrote {p.name}")
    return 0


