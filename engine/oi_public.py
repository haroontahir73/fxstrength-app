"""Public Open Interest view, CFTC-sourced (PR #13).

This replaces the CME-derived public OI numbers with the CFTC Commitments of Traders open
interest already generated by the PR #12 pipeline (options_oi.py -> data/options_fe_oi.json).
It only reads that archive and renders HTML - it makes no network request of any kind, and it
does not touch the COT / Myfxbook / divergence / options-FE pipeline.

Why the change: the previous OI page showed CME preliminary open interest, which carries the
CME redistribution/automation concerns from the PR #12 source audit. CFTC public-reporting
data is the preferred source for this public feature and avoids those concerns; it is weekly
rather than daily, so the feature is now weekly.

Each market shows the full breakdown rather than one unexplained number:

    Futures OI      CFTC futures-only open interest (the headline "open interest")
    Options FE OI   combined − futures-only = delta-adjusted options exposure (futures-equiv.)
    Combined OI     CFTC futures-and-options-combined open interest
    Options share   Options FE OI / Combined OI

plus the weekly change in futures OI and a 52-week percentile for context. "Options FE OI" is
a weekly, delta-adjusted options-exposure measure, not a count of option contracts
(options_oi_config.METHODOLOGY).
"""
import datetime as dt
import json
import os as _os
from html import escape as _e
from pathlib import Path

import options_oi_config as _cfg
from config import DATA

ARCHIVE = DATA / "options_fe_oi.json"
STALE_AFTER_DAYS = 10            # one weekly report is ~7 days; >10 days old -> stale chip
HIST_WEEKS = 13                  # weeks shown in a market's detail table


# ---------------------------------------------------------------- helpers
def _load(data=None):
    """Load the PR #12 archive and attach this view's futures-OI headline metrics per market
    (computed here from the raw observations, not the options-FE metrics stored in the file)."""
    p = Path(data or DATA) / ARCHIVE.name
    if not p.exists():
        return None
    try:
        view = json.loads(p.read_text())
    except ValueError:
        return None
    if not isinstance(view, dict) or "markets" not in view:
        return None
    for m in view["markets"].values():
        m["metrics"] = market_view(m.get("observations") or [])
    view.setdefault("order", _cfg.MARKET_ORDER)
    return view


def _sgn(v):
    if v is None:
        return "&mdash;"
    return f'<span class="{"pos" if v >= 0 else "neg"}">{v:+,}</span>'


def _pctile(series, value):
    """Inclusive 0-100 rank of value within series (same convention as options_oi)."""
    if not series:
        return None
    return round(sum(1 for v in series if v <= value) / len(series) * 100, 1)


def market_view(obs):
    """Per-market presentation numbers computed from the observation list (oldest first).
    Futures-OI headline metrics are derived here; the options-FE metrics mirror options_oi."""
    if not obs:
        return {"available": False}
    fo = [o["futures_only_oi"] for o in obs]
    fe = [o["options_fe_oi"] for o in obs]
    last = obs[-1]
    prev_fo = fo[-2] if len(fo) >= 2 else None
    fo_chg = (fo[-1] - prev_fo) if prev_fo is not None else None
    fo_pct = (fo_chg / prev_fo * 100) if prev_fo not in (None, 0) else None
    win_fo, win_fe = fo[-_cfg.LONG_WIN:], fe[-_cfg.LONG_WIN:]
    return {
        "available": True,
        "date": last["date"],
        "futures_only_oi": last["futures_only_oi"],
        "options_fe_oi": last["options_fe_oi"],
        "combined_oi": last["combined_oi"],
        "options_share": last["options_share"],
        "fo_weekly_change": fo_chg,
        "fo_weekly_pct": fo_pct,
        "fo_pctile_52w": _pctile(win_fo, fo[-1]),
        "fe_pctile_52w": _pctile(win_fe, fe[-1]),
        "sample_weeks": len(fo),
        "window_weeks": len(win_fo),
        "history": obs[-HIST_WEEKS:][::-1],         # newest first, for the detail table
    }


# ---------------------------------------------------------------- freshness
def _freshness(view, now):
    """(report_date, generated_label, stale_flag, note_html)."""
    dates = [m["metrics"]["date"] for m in view["markets"].values()
             if m["metrics"].get("available")]
    report = max(dates) if dates else None
    gen = view.get("generated_at", "")
    stale = False
    if report:
        try:
            age = (now.date() - dt.date.fromisoformat(report)).days
            stale = age > STALE_AFTER_DAYS
        except ValueError:
            pass
    return report, gen, stale


# ---------------------------------------------------------------- rendering
_INTRO = (
    "Open interest is how many futures contracts are still open — it rises when new money "
    "opens a position and falls when someone closes one, so it is the conviction behind a move. "
    "These figures are the CFTC's weekly Commitments of Traders open interest.")

_METH = (
    "<b>Options FE OI</b> is the CFTC's futures-and-options-combined open interest minus its "
    "futures-only open interest: the options folded into the futures contract they are options "
    "on, delta-adjusted into futures-equivalent contracts. " + _cfg.METHODOLOGY +
    " It says nothing about calls, puts, strikes or expiries — those need a licensed "
    "options-chain source.")


def _summary_table(view):
    rows = []
    for key in view["order"]:
        m = view["markets"][key]
        mt = m["metrics"]
        if not mt.get("available"):
            rows.append(f'<tr><td class="pr">{_e(m["label"])}</td>'
                        f'<td class="num mut" colspan="6">no matching CFTC report</td></tr>')
            continue
        share = f'{mt["options_share"] * 100:.1f}%' if mt["options_share"] is not None else "&mdash;"
        pct = "&mdash;" if mt["fo_pctile_52w"] is None else f'{mt["fo_pctile_52w"]:.0f}'
        pctpc = f'{mt["fo_weekly_pct"]:+.2f}%' if mt["fo_weekly_pct"] is not None else "&mdash;"
        rows.append(
            f'<tr><td class="pr">{_e(m["label"])}</td>'
            f'<td class="num mono">{mt["futures_only_oi"]:,}</td>'
            f'<td class="num mono">{mt["options_fe_oi"]:,}</td>'
            f'<td class="num mono">{mt["combined_oi"]:,}</td>'
            f'<td class="num mono">{share}</td>'
            f'<td class="num mono">{_sgn(mt["fo_weekly_change"])} '
            f'<span class="mut">{pctpc}</span></td>'
            f'<td class="num mono mut" title="futures-OI percentile in its last '
            f'{mt["window_weeks"]} weeks">{pct}</td></tr>')
    return ('<div class="tw"><table><thead><tr>'
            '<th>Market</th><th class="num">Futures OI</th><th class="num">Options FE OI</th>'
            '<th class="num">Combined OI</th><th class="num">Options share</th>'
            '<th class="num">&Delta; week (futures)</th><th class="num">52w %ile</th>'
            '</tr></thead><tbody>' + "".join(rows) + '</tbody></table></div>')


def _market_cards(view):
    cards = []
    for key in view["order"]:
        m = view["markets"][key]
        mt = m["metrics"]
        if not mt.get("available"):
            continue
        hrows = []
        for o in mt["history"]:
            share = f'{o["options_share"] * 100:.1f}%' if o["options_share"] is not None else "&mdash;"
            hrows.append(
                f'<tr><td class="mono">{_e(o["date"])}</td>'
                f'<td class="num mono">{o["futures_only_oi"]:,}</td>'
                f'<td class="num mono">{o["options_fe_oi"]:,}</td>'
                f'<td class="num mono">{o["combined_oi"]:,}</td>'
                f'<td class="num mono mut">{share}</td></tr>')
        fe_pct = "&mdash;" if mt["fe_pctile_52w"] is None else f'{mt["fe_pctile_52w"]:.0f}'
        cards.append(
            f'<details class="cotcard oicard"><summary><b>{_e(m["label"])}</b> '
            f'<span class="mut">Futures {mt["futures_only_oi"]:,} &middot; '
            f'Options FE {mt["options_fe_oi"]:,} &middot; share '
            f'{mt["options_share"] * 100:.1f}%</span></summary>'
            f'<p class="mut oihint">Options FE OI 52-week percentile: {fe_pct} '
            f'(last {mt["window_weeks"]} weeks). Weekly history, newest first:</p>'
            '<div class="tw"><table><thead><tr><th>Week</th><th class="num">Futures OI</th>'
            '<th class="num">Options FE OI</th><th class="num">Combined OI</th>'
            '<th class="num">Share</th></tr></thead><tbody>'
            + "".join(hrows) + '</tbody></table></div></details>')
    return '<div class="cotgrid oigrid">' + "".join(cards) + '</div>'


def _unavailable(msg):
    return (f'<section><h2>Open interest</h2>'
            f'<p class="sub">{msg}</p></section>')


def _body(view, now, standalone):
    report, gen, stale = _freshness(view, now)
    if not report:
        return _unavailable("No CFTC open-interest data on file yet.")
    try:
        rlabel = dt.date.fromisoformat(report).strftime("%a %d %b %Y")
    except ValueError:
        rlabel = report
    chip = ('<span class="oistale old">Stale &mdash; the latest CFTC report is from '
            f'{rlabel}</span>' if stale
            else f'<span class="oistale ok">Latest CFTC report: {rlabel}</span>')
    sub = "font-weight:400;font-size:14px"
    return (f'<section>'
            f'<h2>Open interest <span class="mut" style="{sub}">&mdash; CFTC weekly</span></h2>'
            f'<p class="sub">{_INTRO} {chip}</p>'
            + _summary_table(view)
            + '<p class="sub oimeth">' + _METH + '</p>'
            + ('<h3 class="oih3">By market &mdash; weekly history</h3>' if standalone else
               '<p class="sub">Tap a market for its weekly history and percentiles.</p>')
            + _market_cards(view)
            + f'<p class="sub mut" style="margin-top:14px">Source: CFTC Commitments of Traders '
            f'(Traders in Financial Futures for FX, Disaggregated for commodities), '
            f'futures-only and futures-and-options-combined. Generated {_e(gen)}.</p>'
            '</section>')


def panel(now=None, data=None):
    """The dashboard Open interest tab (wrapped by build_dashboard in id='p-oi')."""
    view = _load(data)
    if not view:
        return _unavailable("No CFTC open-interest data on file yet.")
    return _body(view, now or dt.datetime.now(dt.timezone.utc), standalone=False)


def page_body(now=None, data=None):
    """The standalone open-interest.html body (fuller, all markets expanded by default)."""
    view = _load(data)
    if not view:
        return _unavailable("No CFTC open-interest data on file yet.")
    return _body(view, now or dt.datetime.now(dt.timezone.utc), standalone=True)


# ---------------------------------------------------------------- standalone page + CLI
def _summary_line(view):
    """One line for the desk strip: markets with the biggest weekly futures-OI rise / fall."""
    moves = []
    for key in view["order"]:
        mt = view["markets"][key]["metrics"]
        if mt.get("available") and mt.get("fo_weekly_change") is not None:
            moves.append((view["markets"][key]["label"], mt["fo_weekly_change"]))
    ups = [n for n, c in sorted(moves, key=lambda x: -x[1]) if c > 0][:3]
    downs = [n for n, c in sorted(moves, key=lambda x: x[1]) if c < 0][:3]
    return ups, downs


